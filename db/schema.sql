-- FinFlow schema
-- All primary keys are integers. Neon Auth users are mapped to local integer ids.

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id  TEXT NOT NULL UNIQUE,
  email         TEXT NOT NULL DEFAULT '',
  name          TEXT,
  status        TEXT NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'inactive', 'archive', 'failed')),
  status_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  archived_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Existing databases created before account status tracking was added.
ALTER TABLE users ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active';
ALTER TABLE users ADD COLUMN IF NOT EXISTS status_updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE users ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_status_check;
ALTER TABLE users ADD CONSTRAINT users_status_check
  CHECK (status IN ('active', 'inactive', 'archive', 'failed'));

CREATE TABLE IF NOT EXISTS incomes (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  month       DATE NOT NULL,
  source      VARCHAR(120) NOT NULL,
  category    VARCHAR(40) NOT NULL DEFAULT 'salary',
  amount      NUMERIC(18, 8) NOT NULL CHECK (amount > 0),
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS incomes_user_month_idx ON incomes (user_id, month);

-- Amounts are stored in USD; higher precision keeps a foreign-currency entry
-- from drifting when it is converted back for display.
ALTER TABLE incomes ALTER COLUMN amount TYPE NUMERIC(18, 8);

CREATE TABLE IF NOT EXISTS expenses (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  spent_on        DATE NOT NULL,
  title           VARCHAR(160) NOT NULL,
  category        VARCHAR(40) NOT NULL DEFAULT 'other',
  amount          NUMERIC(18, 8) NOT NULL CHECK (amount > 0),
  payment_method  VARCHAR(30) NOT NULL DEFAULT 'card',
  note            TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS expenses_user_spent_on_idx ON expenses (user_id, spent_on);
CREATE INDEX IF NOT EXISTS expenses_user_category_idx ON expenses (user_id, category);

ALTER TABLE expenses ALTER COLUMN amount TYPE NUMERIC(18, 8);
